#!/usr/bin/env python3
"""Generates App/zh-Hant-HK.lproj and App/zh-Hant-TW.lproj strings files and checks key coverage."""
import pathlib, re, sys
sys.path.insert(0, str(pathlib.Path(__file__).parent))
from l10n_table import TW, INFO_PLIST

root = pathlib.Path(__file__).resolve().parent.parent
app = root / "App"

used = set()
for f in app.rglob("*.swift"):
    used.update(m.group(1) for m in re.finditer(r'\btr\("((?:[^"\\\n]|\\.)*)"', f.read_text()))
# Keys fed in from AppCore constants.
used.add("移除廣告")

missing = sorted(used - TW.keys())
unused = sorted(TW.keys() - used)
if missing:
    sys.exit("Missing TW translations:\n" + "\n".join(missing))

def esc(s):
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")

def write(lang, pairs, name):
    d = app / f"{lang}.lproj"
    d.mkdir(exist_ok=True)
    body = "/* Generated by scripts/gen_l10n.py. Edit scripts/l10n_table.py instead. */\n\n"
    body += "".join(f'"{esc(k)}" = "{esc(v)}";\n' for k, v in pairs)
    (d / name).write_text(body, encoding="utf-8")

keys = sorted(TW)
write("zh-Hant-HK", [(k, k) for k in keys], "Localizable.strings")
write("zh-Hant-TW", [(k, TW[k]) for k in keys], "Localizable.strings")
for lang, pairs in INFO_PLIST.items():
    write(lang, sorted(pairs.items()), "InfoPlist.strings")

cantonese = ["㩒", "揀", "嘅", "咗", "唔", "係", "喇", "緊", "幾多", "呢", "嚟", "冇", "嗰", "我哋", "搵", "炒倍"]
bad = [(k, v, p) for k, v in TW.items() for p in cantonese if p in v]
if bad:
    sys.exit("Cantonese in TW strings: " + repr(bad))
print(f"{len(keys)} keys written; unused keys: {unused}")
